"use client";

import * as React from "react";
import * as SwitchPrimitives from "@radix-ui/react-switch";
import { cn } from "@/lib/utils";

/**
 * Switch (DS §20.2): 28 × 16 track, 12 px thumb. Off = surface-4 + fg-3, on = brand-600 + white.
 * The thumb travels toward inline-end via --cls-dir so it is correct in RTL.
 */
const Switch = React.forwardRef<
  React.ElementRef<typeof SwitchPrimitives.Root>,
  React.ComponentPropsWithoutRef<typeof SwitchPrimitives.Root>
>(({ className, ...props }, ref) => (
  <SwitchPrimitives.Root
    className={cn(
      "peer inline-flex h-4 w-7 shrink-0 cursor-pointer items-center rounded-full p-0.5 transition-colors duration-micro",
      "disabled:cursor-not-allowed disabled:opacity-50",
      "data-[state=checked]:bg-brand-600 data-[state=unchecked]:bg-surface-4",
      className,
    )}
    {...props}
    ref={ref}
  >
    <SwitchPrimitives.Thumb
      className={cn(
        "pointer-events-none block size-3 rounded-full transition-transform duration-micro ease-cls-out",
        "data-[state=checked]:translate-x-[calc(var(--cls-dir)*12px)] data-[state=checked]:bg-white",
        "data-[state=unchecked]:translate-x-0 data-[state=unchecked]:bg-fg-3",
      )}
    />
  </SwitchPrimitives.Root>
));
Switch.displayName = SwitchPrimitives.Root.displayName;

export { Switch };
