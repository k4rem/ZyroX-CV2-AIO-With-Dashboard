from __future__ import annotations

from colorama import Fore, Style
from core import zyrox

from cogs.cog_loader import load_all_cogs
from utils.config import BotName


async def setup(bot: zyrox):
    health = await load_all_cogs(bot)
    bot._module_health = health
    health.print_summary()

    if not health.healthy:
        print(
            Fore.RED
            + Style.BRIGHT
            + "Required module load failures detected — review module health summary above."
        )

    print(Fore.RED + Style.BRIGHT + f"All {BotName} cog loading finished.")
